export async function extendPost(postId: string): Promise<{ error: string | null }> {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated' }

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const db = supabase as any
  const { data: post } = await db
    .from('bulletin_posts')
    .select('id, member_id, status, required_by, board_type')
    .eq('id', postId)
    .maybeSingle() as { data: { id: string; member_id: string; status: string; required_by: string; board_type: string } | null }
  if (!post) return { error: 'Post not found' }
  if (post.member_id !== user.id) return { error: 'Only the post author can extend it' }
  if (post.status !== 'open') return { error: 'Only open posts can be extended' }

  // Extend by 14 days from current required_by.
  const current = new Date(post.required_by)
  current.setDate(current.getDate() + 14)
  const newDate = current.toISOString().split('T')[0]

  const { error } = await db
    .from('bulletin_posts')
    .update({ required_by: newDate, expiry_warned_at: null })
    .eq('id', postId)
  if (error) return { error: error.message }

  const extendBasePath = post.board_type === 'community' ? '/community' : '/bulletin'
  revalidatePath(`${extendBasePath}/${postId}`)
  return { error: null }
}

export interface MentionResult {
  id: string
  name: string
  handle: string
  type: 'member' | 'business'
  avatar_url: string | null
  subtitle: string | null
}

export async function searchMembersForMention(query: string): Promise<MentionResult[]> {
  if (!query || query.length < 1) return []
  if (/[,()*]/.test(query)) return []

  const supabase = await createClient()
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const db = supabase as any
  const safe = query.replace(/[%_\\]/g, m => '\\' + m)

  const [{ data: profiles }, { data: businesses }] = await Promise.all([
    db.from('profiles')
      .select('id, full_name, eo_chapter, avatar_url')
      .ilike('full_name', `%${safe}%`)
      .eq('status', 'active')
      .limit(5) as Promise<{ data: Array<{ id: string; full_name: string | null; eo_chapter: string | null; avatar_url: string | null }> | null }>,
    db.from('businesses')
      .select('id, name')
      .ilike('name', `%${safe}%`)
      .eq('status', 'published')
      .limit(4) as Promise<{ data: Array<{ id: string; name: string }> | null }>,
  ])

  const members: MentionResult[] = (profiles ?? [])
    .filter(p => p.full_name)
    .map(p => ({
      id: p.id,
      name: p.full_name!,
      handle: p.full_name!.replace(/\s+/g, '.'),
      type: 'member' as const,
      avatar_url: p.avatar_url,
      subtitle: p.eo_chapter,
    }))

  const bizs: MentionResult[] = (businesses ?? []).map(b => ({
    id: b.id,
    name: b.name,
    handle: b.name.replace(/\s+/g, '.'),
    type: 'business' as const,
    avatar_url: null,
    subtitle: 'Business',
  }))

  return [...members, ...bizs].slice(0, 8)
}
