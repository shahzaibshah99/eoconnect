// Used by the review step: just the free-form description + location + date.
// Title and category are generated by AI, not entered by the user.
const ReviewInputSchema = z.object({
  detail: z.string().trim().min(10, 'Please describe your need in at least 10 characters'),
  geography_country: z.string().trim().min(1, 'Country is required'),
  geography_city: z.string().trim().optional().or(z.literal('')),
  required_by: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Required by must be a date (YYYY-MM-DD)'),
})

// Used by the submit step: title comes from AI (editable by user), category derived from tags.
const PostSchema = z.object({
  title: z.string().trim().min(1, 'Title is required').max(120),
  detail: z.string().trim().max(2000).optional().or(z.literal('')),
  category: z.string().trim().default('General'),
  geography_country: z.string().trim().min(1, 'Country is required'),
  geography_city: z.string().trim().optional().or(z.literal('')),
  required_by: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Required by must be a date (YYYY-MM-DD)'),
  tags: z.array(z.string()).max(20).optional(),
  board_type: z.enum(['business', 'community']).optional(),
})

const ReplySchema = z.object({
  post_id: z.string().uuid(),
  content: z.string().trim().min(1, 'Reply cannot be empty').max(2000),
})

// ── AI review step ─────────────────────────────────────────────

/**
 * Step 1 of the post wizard. Runs AI review on the draft post and
 * returns tags + feedback. Does NOT write to the DB — the member
 * sees the feedback and can either fix it or post anyway.
 *
 * Exported as a server action so the client form can call it on
 * the "Next →" click without page navigation.
 */
export async function reviewPost(input: unknown): Promise<{
  error: string | null
  suggested_title: string | null
  feedback: string | null
  tags: string[]
  is_complete: boolean
}> {
  const supabase = await createClient()
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const db = supabase as any
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated', suggested_title: null, feedback: null, tags: [], is_complete: true }

  const gate = await requireVerified(db, user.id)
  if (!gate.ok) return { error: gate.reason ?? 'Not allowed', suggested_title: null, feedback: null, tags: [], is_complete: true }

  const parsed = ReviewInputSchema.safeParse(input)
  if (!parsed.success) {
    return { error: parsed.error.issues[0].message, suggested_title: null, feedback: null, tags: [], is_complete: true }
  }

  const geo = [parsed.data.geography_city, parsed.data.geography_country].filter(Boolean).join(', ')
  const result = await reviewBulletinPost({
    detail: parsed.data.detail,
    geography: geo,
    required_by: parsed.data.required_by,
  })

  return { error: null, ...result }
}

// ── Submit (Step 2) ────────────────────────────────────────────

/**
 * Step 2: Member confirms the post (with or without addressing AI
 * feedback). Creates the bulletin_post row, then fires the matching
 * engine to notify up to 6 relevant businesses by email.
 *
 * Returns the post ID and matched businesses for the receipt screen.
 */
export async function submitBulletinPost(input: unknown): Promise<{
  error: string | null
  post_id?: string
  matched_businesses?: Array<{ id: string; name: string }>
  matched_members?: Array<{ id: string; name: string }>
  ai_referrals?: ReferralSearchResult[]
}> {
  const supabase = await createClient()
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const db = supabase as any
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return { error: 'Not authenticated' }

  const gate = await requireVerified(db, user.id)
  if (!gate.ok) return { error: gate.reason ?? 'Not allowed' }

  const parsed = PostSchema.safeParse(input)
  if (!parsed.success) return { error: parsed.error.issues[0].message }

  // Refuse if required_by is in the past.
  const today = new Date().toISOString().split('T')[0]
  if (parsed.data.required_by < today) {
    return { error: 'Required by date cannot be in the past' }
  }

  // Fetch poster's name for email notifications.
  const { data: poster } = await db
    .from('profiles')
    .select('full_name, eo_membership_email')
    .eq('id', user.id)
    .maybeSingle() as { data: { full_name: string | null; eo_membership_email: string | null } | null }

  // Insert the post.
  const { data: post, error: postErr } = await db
    .from('bulletin_posts')
    .insert({
      member_id: user.id,
      board_type: parsed.data.board_type ?? 'business',
      title: parsed.data.title,
      detail: parsed.data.detail || null,
      category: parsed.data.category,
      tags: parsed.data.tags ?? [],
      geography_country: parsed.data.geography_country,
      geography_city: parsed.data.geography_city || null,
      required_by: parsed.data.required_by,
      status: 'open',
      ai_reviewed_at: new Date().toISOString(),
      tenant_id: currentTenant(),
    })
    .select('id')
    .maybeSingle() as { data: { id: string } | null; error: { message: string } | null }

  if (postErr || !post) return { error: postErr?.message ?? 'Failed to create post' }

  // ── Matching / notification engine ───────────────────────────
  // business board → match businesses by tag + geography
  // community board → notify verified members in the same country
  const boardType = (parsed.data.board_type ?? 'business') as 'business' | 'community'
  let matched: Array<{ id: string; name: string }> = []
  let matchedMembers: Array<{ id: string; name: string }> = []

  if (boardType === 'community') {
    // Generate AI tagline for community asks in the background — best-effort.
    void generateCommunityTagline({
      title: parsed.data.title,
      detail: parsed.data.detail ?? '',
      category: parsed.data.category,
    }).then(tagline => {
      if (tagline) {
        db.from('bulletin_posts').update({ ai_tagline: tagline }).eq('id', post.id)
          // eslint-disable-next-line @typescript-eslint/no-explicit-any
          .then(({ error }: { error: any }) => { if (error) console.error('[tagline] save failed:', error.message) })
      }
    }).catch(err => console.error('[tagline] generation failed:', err))

    matchedMembers = await notifyMembersGeo({
      postId: post.id,
      country: parsed.data.geography_country,
      city: parsed.data.geography_city ?? null,
      postTitle: parsed.data.title,
      posterName: poster?.full_name ?? 'A member',
      posterId: user.id,
      siteUrl: siteUrl(),
    })
    if (matchedMembers.length > 0) {
      await db
        .from('bulletin_posts')
        .update({ matched_business_ids: matchedMembers.map(m => m.id) })
        .eq('id', post.id)
    }
  } else {
    matched = await matchAndNotify({
      postId: post.id,
      tags: parsed.data.tags ?? [],
      detail: parsed.data.detail ?? '',
      country: parsed.data.geography_country,
      city: parsed.data.geography_city ?? null,
      postTitle: parsed.data.title,
      posterName: poster?.full_name ?? 'An EO member',
      siteUrl: siteUrl(),
    })
    if (matched.length > 0) {
      await db
        .from('bulletin_posts')
        .update({ matched_business_ids: matched.map(m => m.id) })
        .eq('id', post.id)
    }
  }

  // F18: surface top-3 relevant referrals from the referral DB.
  const queryText = [parsed.data.title, parsed.data.detail].filter(Boolean).join('\n')
  const aiReferrals = await searchReferrals(db, {
    queryText,
    boardType,
    matchCount: 3,
  })

  revalidatePath('/bulletin')
  revalidatePath('/community')
  return { error: null, post_id: post.id, matched_businesses: matched, matched_members: matchedMembers, ai_referrals: aiReferrals }
}

// ── Matching engine ────────────────────────────────────────────

// Extract meaningful lowercase words from tags or free text.
// Splits on hyphens, underscores, spaces; drops stopwords and tokens < 3 chars.
function extractKeywords(texts: string[]): Set<string> {
  const STOP = new Set(['a', 'an', 'the', 'and', 'or', 'for', 'in', 'of', 'to', 'with', 'by', 'at', 'on', 'is', 'are', 'be', 'as', 'we', 'our', 'your'])
  const words = new Set<string>()
  for (const text of texts) {
    text.toLowerCase()
      .replace(/[-_/]/g, ' ')
      .split(/\s+/)
      .forEach(w => {
        const clean = w.replace(/[^a-z0-9]/g, '')
        if (clean.length >= 3 && !STOP.has(clean)) words.add(clean)
      })
  }
  return words
}

// Score how well a business's tags match the need keywords.
// Uses prefix matching so "consult" matches "consulting", "consultant" etc.
function scoreTagMatch(bizTags: string[], needKeywords: Set<string>): number {
  if (!bizTags.length || !needKeywords.size) return 0
  const bizWords = extractKeywords(bizTags)
  let score = 0
  for (const needWord of needKeywords) {
    for (const bizWord of bizWords) {
      if (bizWord === needWord || bizWord.startsWith(needWord) || needWord.startsWith(bizWord)) {
        score++
        break
      }
    }
  }
  return score
}

async function matchAndNotify(input: {
  postId: string
  tags: string[]
  detail?: string
  country: string
  city: string | null
  postTitle: string
  posterName: string
  siteUrl: string
}): Promise<Array<{ id: string; name: string }>> {
  if (!process.env.SUPABASE_SERVICE_ROLE_KEY) return []
  const svc = adminDb()

  type BizRow = {
    id: string; name: string; owner_id: string; tags: string[];
    verification_tag: string | null; created_at: string; country: string | null;
    profiles: { eo_membership_email: string | null; full_name: string | null } | null
  }

  // Fetch all published non-slow-replier businesses in the same country.
  // We score them in JS so tag format differences (kebab, Title Case, etc.)
  // don't prevent a match.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const { data: candidates } = await (svc as any)
    .from('businesses')
    .select('id, name, owner_id, tags, verification_tag, created_at, country, profiles!owner_id(eo_membership_email, full_name)')
    .eq('status', 'published')
    .eq('slow_replier', false)
    .not('owner_id', 'is', null)
    .ilike('country', input.country)
    .limit(200) as { data: BizRow[] | null }

  if (!candidates || candidates.length === 0) return []

  // Build keyword set from need tags + description for richer matching.
  const needKeywords = extractKeywords([...input.tags, input.detail ?? ''])

  // Score each business by word-level overlap with its tags.
  // Sort: score DESC → verification tier → recency. Keep top 6.
  const scored = candidates
    .map(biz => ({ biz, score: scoreTagMatch(biz.tags ?? [], needKeywords) }))
    .filter(({ score }) => score > 0)
    .sort((a, b) => {
      if (b.score !== a.score) return b.score - a.score
      const aTier = VERIFICATION_TIER[a.biz.verification_tag ?? 'unverified'] ?? 99
      const bTier = VERIFICATION_TIER[b.biz.verification_tag ?? 'unverified'] ?? 99
      if (aTier !== bTier) return aTier - bTier
      return new Date(b.biz.created_at).getTime() - new Date(a.biz.created_at).getTime()
    })

  const sorted = scored.slice(0, 6).map(({ biz }) => biz)

  if (sorted.length === 0) return []

  const postUrl = `${input.siteUrl}/bulletin/${input.postId}`

  // Fire match emails — best-effort, don't block on failure.
  for (const biz of sorted) {
    const email = biz.profiles?.eo_membership_email
    if (!email) continue
    sendEmail({
      to: email,
      subject: `New business need matches your listing: "${input.postTitle}"`,
      html: bulletinMatchEmailHtml({
        businessName: biz.name,
        ownerName: biz.profiles?.full_name ?? 'there',
        postTitle: input.postTitle,
        posterName: input.posterName,
        postUrl,
      }),
    }).catch(err => console.error('[bulletin-match] email failed for', biz.id, err))
  }

  return sorted.map(b => ({ id: b.id, name: b.name }))
}

